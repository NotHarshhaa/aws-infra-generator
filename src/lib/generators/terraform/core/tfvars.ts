import { GeneratedFile } from '../types';

export function generateTfvars(
  services: string[],
  config: Record<string, any>,
  environment: string,
  region: string,
  projectName: string,
  options?: {
    ownerEmail?: string;
    costCenter?: string;
  }
): GeneratedFile {
  const lines: string[] = [
    `# ==============================================================================`,
    `# Terraform Variables Configuration`,
    `# Project: ${projectName}`,
    `# Environment: ${environment}`,
    `# Region: ${region}`,
    `# Generated by AWS Infra Generator`,
    `# ==============================================================================`,
    ``,
    `# --- Core Project Settings ---`,
    `aws_region   = "${region}"`,
    `environment  = "${environment}"`,
    `project_name = "${projectName}"`,
    `cost_center  = "${options?.costCenter || 'engineering'}"`,
    `owner_email  = "${options?.ownerEmail || 'admin@example.com'}"`,
    ``,
  ];

  if (services.includes("vpc")) {
    const vpcCfg = config.vpc?.config || {};
    const defaultAzs = [`${region}a`, `${region}b`, `${region}c`];
    const azs = vpcCfg.availability_zones && vpcCfg.availability_zones.length >= 2
      ? vpcCfg.availability_zones
      : defaultAzs;
    lines.push(
      `# --- VPC Configuration ---`,
      `vpc_cidr             = "${vpcCfg.cidr_block || "10.0.0.0/16"}"`,
      `availability_zones   = ${JSON.stringify(azs)}`,
      `enable_nat_gateway   = ${vpcCfg.enable_nat !== false}`,
      `enable_vpc_flow_logs = true`,
      ``
    );
  }

  if (services.includes("ec2")) {
    const ec2Cfg = config.ec2?.config || {};
    lines.push(
      `# --- EC2 Configuration ---`,
      `instance_type    = "${ec2Cfg.instance_type || "t3.medium"}"`,
      `instance_count   = ${ec2Cfg.instance_count || 1}`,
      `root_volume_size = ${ec2Cfg.root_volume_size || 50}`,
      ``
    );
  }

  if (services.includes("s3")) {
    const s3Cfg = config.s3?.config || {};
    lines.push(
      `# --- S3 Configuration ---`,
      `bucket_prefix          = "${s3Cfg.bucket_name || "storage"}"`,
      `enable_s3_versioning   = ${s3Cfg.versioning !== false}`,
      `s3_encryption_enabled  = ${s3Cfg.encryption !== false}`,
      `s3_block_public_access = ${s3Cfg.block_public_access !== false}`,
      ``
    );
  }

  if (services.includes("rds")) {
    const rdsCfg = config.rds?.config || {};
    lines.push(
      `# --- RDS Configuration ---`,
      `db_engine            = "${rdsCfg.engine || "postgres"}"`,
      `db_instance_class    = "${rdsCfg.instance_class || "db.t3.micro"}"`,
      `db_allocated_storage = ${rdsCfg.allocated_storage || 20}`,
      `db_multi_az          = ${rdsCfg.multi_az === true}`,
      ``
    );
  }

  if (services.includes("dynamodb")) {
    const dynamoCfg = config.dynamodb?.config || {};
    lines.push(
      `# --- DynamoDB Configuration ---`,
      `dynamodb_table_name   = "${dynamoCfg.table_name || "table"}"`,
      `dynamodb_billing_mode = "${dynamoCfg.billing_mode || "PAY_PER_REQUEST"}"`,
      ``
    );
  }

  if (services.includes("lambda")) {
    const lambdaCfg = config.lambda?.config || {};
    lines.push(
      `# --- Lambda Configuration ---`,
      `lambda_function_name = "${lambdaCfg.function_name || "api-handler"}"`,
      `lambda_memory_size   = ${lambdaCfg.memory_size || 128}`,
      `lambda_timeout       = ${lambdaCfg.timeout || 10}`,
      ``
    );
  }

  const content = lines.join("\n");

  return {
    name: "terraform.tfvars",
    path: `${projectName}/terraform.tfvars`,
    content,
    language: "hcl",
  };
}
